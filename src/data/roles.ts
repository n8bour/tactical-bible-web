export function groupOf(code: string): PositionGroup {
  if (code === 'GK') return 'GK';
  if (code === 'DL' || code === 'DR') return 'D_LR';
  if (code.startsWith('DC')) return 'DC';
  if (code.startsWith('WB')) return 'WB_LR';
  if (code.startsWith('DM')) return 'DM';
  if (code === 'ML' || code === 'MR') return 'M_LR';
  if (code.startsWith('MC')) return 'MC';
  if (code === 'AML' || code === 'AMR') return 'AM_LR';
  if (code.startsWith('AMC')) return 'AMC';
  if (code.startsWith('ST')) return 'ST';
  return 'MC';
}

export function isWideCBSlot(code: string, slotCodes: readonly string[]): boolean {
  const dcCount = slotCodes.filter((c) => c.startsWith('DC')).length;
  return dcCount >= 3 && (code === 'DCL' || code === 'DCR');
}

export function rolesForSlot(
  code: string,
  slotCodes: readonly string[],
  phase: RolePhase,
): RoleDef[] {
  const g = groupOf(code);
  const wideCB = isWideCBSlot(code, slotCodes);
  return ROLES.filter((r) => {
    if (r.phase !== phase) return false;
    if (!r.groups.includes(g)) return false;
    if (r.wideCB && !wideCB) return false;
    return true;
  });
}
