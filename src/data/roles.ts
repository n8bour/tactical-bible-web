export interface RoleProfileParams {
  /** Vertical tendency relative to slot base (-1 = drops deep, 0 = neutral, +1 = pushes high). */
  depth: number;
  /** Horizontal tendency relative to centre (-1 = tucks narrow/inside, 0 = neutral, +1 = holds touchline width). */
  width: number;
  /** Lateral/ball-side roaming freedom (0..1). */
  roam: number;
  /** On-ball passing/creative risk appetite (0..1). */
  risk: number;
  /** Out-of-possession pressing aggression (0..1). */
  press: number;
  /** Attacks the defensive line or channels in behind (0..1). */
  lineRun: number;
  /** Arrives late into the penalty box (0..1). */
  lateBox: number;
  /** Inverts inward into midfield or half-space (0..1). */
  invert: number;
  /** Overlaps wide down the touchline (0..1). */
  overlap: number;
  /** Drops deep towards build-up or defensive line (0..1). */
  dropDeep: number;
  /** Holds position and anchors rest-defence or defensive block (0..1). */
  holdPos: number;
  /** Parameter provenance tag ('est' for tactical model weights). */
  src: 'conf' | 'est';
  /** Short tactical rationale for the profile weights. */
  note: string;
}

