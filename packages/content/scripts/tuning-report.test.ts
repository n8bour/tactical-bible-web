// Writes packages/content/TUNING.md: for every scene, what the docs promise next to what the simulation shows.
// Run with `npm run tuning:report`. The Status column is kept from the previous file so hand reviews survive.
import { createWorld, metrics, step } from '@tb/sim';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { it } from 'vitest';
import { KNOWLEDGE, OVERRIDES, playerInstructions, ROLES, SCENES, teamInstructions } from '../src';

const OUT = join(__dirname, '..', 'TUNING.md');
const cell = (s: string) => s.replace(/\|/g, '/').replace(/\s+/g, ' ').trim();

function observe(id: string): string {
  const s = SCENES[id];
  const w = createWorld(s, KNOWLEDGE);
  for (let i = 0; i < s.duration * 20; i++) step(w);
  const m = metrics(w, s.focus);
  const mine = w.events.filter((e) => e.agent === s.focus);
  const count = (k: string) => mine.filter((e) => e.kind === k).length;
  return `depth ${m.avgDepth.toFixed(0)} m, width ${m.avgWidth.toFixed(0)} m, ${m.distance.toFixed(0)} m run; runs ${count('run')}, passes ${count('pass') + count('through')}, carries ${count('carry')}, shots ${count('shot')}, presses ${count('press')}; team passes ${m.passes} (${m.passesCompleted} done)`;
}

it('writes TUNING.md', () => {
  const prev = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  const status = (key: string, fallback: string) => prev.match(new RegExp(`^\\| \`${key}\` \\|.*\\| (ok|tuned|open) \\|$`, 'm'))?.[1] ?? fallback;
  const lines = [
    '# Tuning checklist',
    '',
    'Generated by `npm run tuning:report` from the scenes (observed columns are measured from the default scene run).',
    'Status is kept between runs: set it by hand to `ok` after watching the scene, `tuned` after changing `OVERRIDES`, `TI_EFFECTS`/`PI_EFFECTS` or `ATTR_MODEL`, `open` otherwise.',
    'Every tuning change records its reason in the entry\'s `note`.',
    '',
    '## Roles',
    '',
    '| Role | Expected | Observed (focus player, default scene) | Status |',
    '| --- | --- | --- | --- |',
    ...ROLES.map((r) => `| \`${r.id}\` | ${cell(`${r.name}: ${r.moveNote ?? r.desc}`)} | ${observe(`role-${r.id}`)} | ${status(r.id, OVERRIDES[r.id] ? 'tuned' : 'open')} |`),
    '',
    '## Team instructions',
    '',
    '| Instruction | Expected | Observed (default scene, default option) | Status |',
    '| --- | --- | --- | --- |',
    ...teamInstructions.map((t) => `| \`${t.key}\` | ${cell(`${t.name}: ${t.pro}`)} | ${observe(`ti-${t.key}`)} | ${status(t.key, 'open')} |`),
    '',
    '## Player instructions',
    '',
    '| Instruction | Expected | Observed (default scene, instruction off) | Status |',
    '| --- | --- | --- | --- |',
    ...playerInstructions.map((p) => `| \`${p.key}\` | ${cell(`${p.name}: ${p.desc}`)} | ${observe(`pi-${p.key}`)} | ${status(p.key, ['stay_wider', 'press_more'].includes(p.key) ? 'ok' : 'open')} |`),
    '',
  ];
  writeFileSync(OUT, lines.join('\n'));
});
