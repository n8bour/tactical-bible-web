// Regenerates src/roles/profiles.generated.ts from data/roles.json + data/role-anchors.json.
// Drafts only: hand tuning goes in OVERRIDES in src/roles/profiles.ts.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const roles = JSON.parse(readFileSync(join(root, 'data/roles.json'), 'utf8'));
const anchors = JSON.parse(readFileSync(join(root, 'data/role-anchors.json'), 'utf8'));
const r1 = (v) => Math.round(v * 10) / 10;

const out = {};
for (const r of roles) {
  const tags = new Set(r.tags);
  const p = {
    ab: r.ab,
    phase: r.phase,
    anchor: {},
    runs: [],
    onBall: { pass: 0, through: 0, carry: 0, shoot: 0, cross: 0, hold: 0, riskAversion: 0.5 },
    oop: { pressRadius: 9, holdLine: 0, track: 0.5, mark: 'zonal' },
    key: r.key,
    pref: r.pref,
    src: 'est',
  };
  if (r.phase === 'IP') {
    for (const ph of ['build', 'prog', 'final']) {
      const m = r.moves?.[ph];
      const a = {};
      if (m?.y != null) a.depth = r1(m.y * 1.05);
      else if (anchors[r.id]?.phases?.[ph]) a.depth = r1(anchors[r.id].phases[ph].y * 1.05);
      if (m?.x) a.lane = m.x;
      if (m?.xs) a.spread = m.xs;
      p.anchor[ph] = a;
    }
    const run = (kind, phase, prob) => p.runs.push({ kind, phase, p: prob });
    if (tags.has('W')) {
      p.onBall.cross += 0.3;
      for (const ph of ['prog', 'final']) if (!p.anchor[ph].lane) p.anchor[ph].lane = 'wide';
    }
    if (tags.has('IN')) { run('invert', 'prog', 0.7); run('invert', 'final', 0.7); }
    if (tags.has('RD')) { run('hold', 'final', 1); p.onBall.riskAversion += 0.3; }
    if (tags.has('BOX')) run('box_centre', 'final', 0.8);
    if (tags.has('CR')) { p.onBall.through += 0.4; p.onBall.riskAversion -= 0.2; }
    if (tags.has('LINK')) { p.onBall.pass += 0.3; run('drop', 'prog', 0.5); }
    if (tags.has('RUN')) { run('beyond', 'prog', 0.8); run('beyond', 'final', 0.8); }
    if (tags.has('DROP')) run('drop', 'prog', 0.8);
    if (tags.has('AIR')) { run('box_centre', 'final', 0.8); p.onBall.hold += 0.2; }
    if (tags.has('ADV')) run('overlap', 'prog', 0.7);
    if (tags.has('TOCB') && !p.anchor.build.lane) p.anchor.build = { depth: 12, lane: 'cbw' };
    if (tags.has('TODM') && !p.anchor.build.lane) p.anchor.build = { depth: 30, lane: 'c' };
    p.onBall.riskAversion = r1(p.onBall.riskAversion);
  } else {
    if (tags.has('HP')) { p.oop.pressRadius = 14; p.oop.holdLine = 2; }
    if (tags.has('LOW')) { p.oop.pressRadius = 6; p.oop.holdLine = -3; }
    if (tags.has('OUT')) { p.oop.outletDepth = 60; p.oop.track = 0; p.oop.pressRadius = 5; }
    if (tags.has('CW')) p.oop.track = 0.9;
    if (tags.has('TRK')) p.oop.track = 0.8;
  }
  out[r.id] = p;
}

const body = `// Generated by scripts/draft-profiles.mjs from data/roles.json and data/role-anchors.json. Do not edit.
import type { RoleProfile } from '@tb/sim';

export type DraftProfile = RoleProfile & { ab: string; phase: 'IP' | 'OOP' };

export const DRAFT_PROFILES: Record<string, DraftProfile> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(join(root, 'src/roles/profiles.generated.ts'), body);
console.log('profiles', Object.keys(out).length);
